defmodule MarshallWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :marshall

  # The session is stored in a signed and encrypted cookie. MarshallWeb.BrowserSession
  # owns the options so Plug.Session, the LiveView socket and every test or
  # probe that forges a session agree on the cookie name, salts and attributes.
  @session_options MarshallWeb.BrowserSession.options()

  # @cc [owner:ghuntley,label:architecture;recovery] live-socket-websocket-only
  # The LiveView socket MUST offer only the WebSocket transport. Marshall
  # replicas share no PubSub (ADR-0141) behind a round-robin proxy, so a
  # long-poll session is node-local and cannot be resumed by its next request.
  socket "/live", MarshallWeb.LiveSocket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: false

  # @cc [owner:ghuntley,label:security] endpoint-privacy-before-diagnostics
  # AuthenticationPrivacy MUST run before request loggers, telemetry and body
  # parsers so token-bearing request paths are tagged before diagnostics occur.
  plug MarshallWeb.AuthenticationPrivacy
  # SecurityHeaders and NoIndex run before health, static files and the early
  # /api refusals so every response carries the same browser policy.
  plug MarshallWeb.SecurityHeaders
  plug MarshallWeb.NoIndex
  plug MarshallWeb.Health

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug :scim_dispatch

  plug Plug.Static,
    at: "/",
    from: :marshall,
    gzip: not code_reloading?,
    only: MarshallWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :marshall
  end

  # @cc [owner:ghuntley,label:security] public-machine-api-refusal
  # The browser endpoint MUST refuse reserved machine API paths before browser
  # sessions, body parsing and diagnostics. Only current public SSH key discovery
  # may pass within those prefixes; credentials MUST NOT select fleet dispatch.
  # Machine APIs are served exclusively by the separate fleet transport.
  plug MarshallWeb.PublicIngress

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug MarshallWeb.BrowserSession
  plug MarshallWeb.ObservedRouter

  @spec scim_dispatch(Plug.Conn.t(), keyword()) :: Plug.Conn.t()
  defp scim_dispatch(%Plug.Conn{path_info: ["scim", "v2" | rest]} = conn, _opts) do
    conn = %{conn | path_info: rest, script_name: conn.script_name ++ ["scim", "v2"]}
    # The SCIM router sends its own response; halt so no later endpoint plug
    # touches the already-sent connection.
    conn
    |> MarshallWeb.ScimRouter.call(MarshallWeb.ScimRouter.init([]))
    |> Plug.Conn.halt()
  end

  defp scim_dispatch(conn, _opts), do: conn
end
