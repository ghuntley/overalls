#!/usr/bin/env bash
# Regenerates nix/buck/assembly_attrs.bzl from lib.assemble's flake package
# outputs and check names; BUCK.v2 declares a nix_assemble target for each
# (ADR-0269). Evaluates names only.
set -euo pipefail
cd "$(dirname "$0")/../.."
names() { nix eval --json .#lib.assemble --apply "assemble: builtins.attrNames (assemble { }).$1"; }
{
  echo "# Generated by nix/buck/assembly-attrs.sh; do not edit."
  echo "ASSEMBLY_PACKAGES = $(names outputPackages)"
  echo "ASSEMBLY_CHECKS = $(names checks)"
} > nix/buck/assembly_attrs.bzl
