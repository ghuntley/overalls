#!/usr/bin/env bash
# Regenerates nix/buck/bootstrap_attrs.bzl from the flake's package and check
# names. Deleted with nix_flake_attr (ADR-0269).
set -euo pipefail
cd "$(dirname "$0")/../.."
names() { nix eval --json ".#$1.x86_64-linux" --apply builtins.attrNames 2>/dev/null; }
{
  echo "# Generated by nix/buck/bootstrap-attrs.sh; do not edit."
  echo "BOOTSTRAP_PACKAGES = $(names packages)"
  echo "BOOTSTRAP_CHECKS = $(names checks)"
} > nix/buck/bootstrap_attrs.bzl
