"""NixOS machine tests as Buck2 targets (ADR-0270).

Subcommands:
  generate           write nix/verification/tests/machines/**/BUCK from catalog.nix
  check              fail when the generated files are stale or their labels differ
                     from the suites' declared requiredFeatures
  refresh-scenarios  re-derive fleet/scenarios.json by evaluating each fleet
                     variant's test script (evaluation only, no derivation build)
  run                the test command of one nixos_machine_test target

Contract nixos-machine-test-labels and machine-test-targets-generated: see buck/CONTRACTS.
"""

